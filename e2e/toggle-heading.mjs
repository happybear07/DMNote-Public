// 노션 토글 제목: /토글 제목 1 → 제목 모양 요약 줄의 토글, Enter로 안쪽 내용, 접기 단추가 제목 줄 가운데, 접으면 내용 숨김 — 문서 뷰.
// 사용: dev 서버 실행 후 `node e2e/toggle-heading.mjs [스크린샷 폴더]`
import { chromium } from 'playwright-core';

const BASE = process.env.DN_URL ?? 'http://localhost:5173';
const OUT = process.argv[2];
const results = [];
const check = (name, ok, detail = '') => { results.push({ name, ok }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? ` — ${detail}` : ''}`); };
const browser = await chromium.launch({ channel: process.env.DN_CHANNEL ?? 'msedge', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem('dn:no-env-key', '1'));
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error' && !/favicon/.test(m.text())) errors.push(m.text()); });
const ws = (fn, arg) => page.evaluate(fn, arg);
const wait = (ms) => page.waitForTimeout(ms);
await page.goto(BASE);
await page.waitForSelector('.dn-block', { timeout: 15000 });
await ws(() => window.__dn.newNote());
await wait(300);
await ws(() => window.__dn.setViewMode('doc'));
await wait(400);
await page.locator('.dn-doc-page').click({ position: { x: 300, y: 200 } });
await wait(200);
await page.keyboard.type('/');
await wait(120);
await page.keyboard.type('토글 제목 1');
await wait(250);
const first = await page.locator('.dn-slash .dn-slash-item').first().innerText();
await page.keyboard.press('Enter');
await wait(300);
await page.keyboard.type('접히는 제목');
await page.keyboard.press('Enter');
await page.keyboard.type('안쪽 내용 한 줄');
await wait(300);
const doc = await ws(() => JSON.stringify([...window.__dn.view.engine.contents()][0]?.doc ?? ''));
check('/토글 제목 1 → 메뉴 맨 위', first.includes('토글 제목 1'), first.replace(/\n/g, ' '));
check('제목(H1) 요약 줄 + 안쪽 문단의 토글', /"type":"toggle".*"type":"heading","attrs":\{"level":1\}.*접히는 제목.*"type":"paragraph".*안쪽 내용 한 줄/.test(doc), doc.slice(0, 220));
const geo = await ws(() => { const t = document.querySelector('.dn-doc [data-type="toggle"]'); const b = t.querySelector('.dn-toggle-btn').getBoundingClientRect(), h = t.querySelector('.dn-toggle-body > h1').getBoundingClientRect(); return { btnMid: Math.round(b.top + b.height / 2), lineMid: Math.round(h.top + parseFloat(getComputedStyle(t.querySelector('.dn-toggle-body > h1')).lineHeight) / 2) }; });
check('접기 단추가 제목 첫 줄 가운데', Math.abs(geo.btnMid - geo.lineMid) <= 2, JSON.stringify(geo));
if (OUT) await page.screenshot({ path: `${OUT}/toggle-heading.png` });
await page.locator('.dn-doc [data-type="toggle"] .dn-toggle-btn').click();
await wait(300);
check('단추를 누르면 접혀서 안쪽 내용이 숨음', (await page.locator('.dn-doc [data-type="toggle"] .dn-toggle-body > p').first().isVisible()) === false);
check('콘솔 오류 없음', errors.length === 0, errors.join(' | '));
await browser.close();
const bad = results.filter((r) => !r.ok).length;
console.log(`\n${results.length - bad}/${results.length} passed`);
process.exit(bad ? 1 : 0);
